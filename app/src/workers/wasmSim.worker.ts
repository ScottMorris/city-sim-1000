/** Fiscal policy as a flat tuple-ish record (mirrors SimHost.set_budget_policy args). */
export interface WorkerBudgetPolicy {
  taxResidential: number;
  taxCommercial: number;
  taxIndustrial: number;
  fundTransport: number;
  fundPower: number;
  fundCivic: number;
}

