function applyPolicy(h: SimHost, p: WorkerBudgetPolicy) {
  h.set_budget_policy(
    p.taxResidential,
    p.taxCommercial,
    p.taxIndustrial,
    p.fundTransport,
    p.fundPower,
    p.fundCivic,
  );
}

