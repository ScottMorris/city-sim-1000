/**
 * wasmSim.worker.ts — Web Worker that owns the WASM SimHost.
 *
 * Protocol (both directions use structured-clone via postMessage):
 *
 * Main → Worker:
 *   { type: 'init';       payload: { width: number; height: number; seed: number } }
 *   { type: 'step';       payload: { dt: number } }
 *   { type: 'apply_tool'; payload: { tool: number; x: number; y: number } }
 *   { type: 'set_speed';  payload: { multiplier: number } }
 *   { type: 'undo' }
 *   { type: 'reset';      payload: { width: number; height: number; seed: number } }
 *
 * Worker → Main:
 *   { type: 'ready' }
 *   { type: 'step_result';  bytes: Uint8Array; stats: SimStats }  (buffer transferred)
 *   { type: 'apply_result'; success: boolean }
 *   { type: 'undo_result';  happened: false }
 *   { type: 'undo_result';  happened: true; bytes: Uint8Array; stats: SimStats }
 */
